"""Rebuild every derived table in data\\ from a bootstrap folder, and compare with the committed tables.

usage: build_tables.py BOOT_DIR [--out DIR] [--only a,b,...] [--check] [--adopt] [--ghidra] [--game GAME_DIR]

BOOT_DIR is the folder written by bootstrap.py (needs the steps scripts, configs, ce, lang and dz). Tables are written to
a fresh staging folder (stage_XXXX) inside --out (default BOOT_DIR\\tables), so nothing from an earlier run can be mistaken for
a result of this one. Nothing already in --out is read, cleared or deleted (CODEX.md CXR-008); only the staging folder this
run created is removed at the end (--keep leaves it for inspection). Every staged table must have rows as wide as its header
(CXR-009) or the build counts as incomplete. --out may not overlap an input folder (boot cfg/scripts_src/ce/dz, the game, data\\).

  --check   compare every requested table with data\\<table>.csv (complete comparison, see csv_diff.py)
  --adopt   copy the rebuilt tables into data\\. Adoption happens only when every requested table was generated by this run
            and every generator succeeded (CODEX.md CXR-007); a data difference does not block adoption, a failed or
            incomplete build does. Nothing is copied unless all requested tables can be copied.
  --only    comma-separated table names (validated against the known tables)
  --ghidra  also rebuild native_api and native_unmatched (needs the persistent Ghidra project, several minutes); without it
            these two are not requested and are reported as skipped

Tables that cannot be rebuilt (message_ids, message_map) are reported as manual and never touched.
Exit code 0 only when the build is complete and, with --check, every requested table is identical (with --adopt a data
difference is allowed). Refuses a BOOT_DIR or --out inside the project folder. Read-only on the game files.
"""
import argparse
import os
import shutil
import subprocess
import sys
import tempfile

HERE = os.path.dirname(os.path.abspath(__file__))
PROJECT = os.path.dirname(HERE)
DATA = os.path.join(PROJECT, "data")
PY = [sys.executable, "-I"]

# table -> columns used to pair rows in the comparison report (the comparison itself uses whole rows)
KEYS = {"ammo": "name", "ammo_physics": "name", "explosives": "name", "body_zones": "class,zone", "clothing": "name",
        "script_decls": "Name,File", "melee": "name", "recoil": "Name", "food": "name", "weapons": "name",
        "loot_types_chernarus": "name", "loot_types_enoch": "name", "loot_types_nasdara": "name",
        "loot_types_sakhal": "name", "maps_compare": "map", "recipes": "class", "items_master": "name",
        "food_stages": "item,stage", "actions": "action", "weapon_states": "mechanism,var", "weapon_transitions": "mechanism,from,event,to",
        "vehicles": "name", "catching_items": "name", "penetration_materials": "material", "ai_perception": "behaviour",
        "noise_sources": "section,class,noise", "archives": "folder,pbo", "native_api": "reg_fn,method,native_fn",
        "native_unmatched": "script_class,method"}
GHIDRA_TABLES = {"native_api", "native_unmatched"}
MANUAL_TABLES = ["message_ids", "message_map"]
CE_MAPS = {"chernarus": "worlds_chernarusplus_ce", "enoch": "worlds_enoch_ce", "nasdara": "worlds_nasdara_ce",
           "sakhal": "worlds_sakhal_ce"}
CONFIG_TABLES = {"ammo", "ammo_physics", "explosives", "body_zones", "clothing", "script_decls", "melee", "recoil", "food",
                 "weapons"}
ITEMS_INPUTS = ["clothing", "weapons", "food", "recipes"] + [f"loot_types_{k}" for k in CE_MAPS]


def run(cmd, label):
    r = subprocess.run(cmd, capture_output=True, text=True)
    if r.returncode != 0:
        print(f"  FAILED {label}: {(r.stderr or r.stdout).strip()[-400:]}")
        return False
    last = (r.stdout.strip().splitlines() or [""])[-1]
    print(f"  {label}: {last}")
    return True


def build(boot, out, game, requested, ghidra):
    """Run the generators for the requested tables; returns True when every generator exited successfully."""
    cfg, scripts = os.path.join(boot, "cfg"), os.path.join(boot, "scripts_src")
    lang = os.path.join(game, "dta", "languagecore.pbo")
    ce = os.path.join(boot, "ce")
    ok = True

    def want(*names):
        return any(n in requested for n in names)
    if want(*CONFIG_TABLES):
        ok &= run(PY + [os.path.join(HERE, "config_tables.py"), cfg, scripts, out, lang], "config tables")
    for key, folder in CE_MAPS.items():
        if want("loot_types_" + key):
            ok &= run(PY + [os.path.join(HERE, "ce_types.py"), "types", os.path.join(ce, folder),
                            os.path.join(out, f"loot_types_{key}.csv")], f"loot_types_{key}")
    if want("maps_compare"):
        ok &= run(PY + [os.path.join(HERE, "ce_types.py"), "compare", ce, os.path.join(out, "maps_compare.csv")], "maps_compare")
    if want("recipes", "items_master"):
        ok &= run(PY + [os.path.join(HERE, "recipes.py"), scripts, os.path.join(out, "recipes.csv"), lang], "recipes")
    if want("items_master"):
        # items_master joins clothing, weapons, food, loot_types and recipes. Its inputs are collected in a separate folder:
        # the tables rebuilt in this run, else the committed ones (so --only items_master works) - never leftovers.
        inputs = os.path.join(out, "_inputs")
        shutil.rmtree(inputs, ignore_errors=True)
        os.makedirs(inputs)
        for need in ITEMS_INPUTS:
            src = os.path.join(out, need + ".csv")
            if not os.path.exists(src):
                src = os.path.join(DATA, need + ".csv")
            shutil.copyfile(src, os.path.join(inputs, need + ".csv"))
        ok &= run(PY + [os.path.join(HERE, "items_master.py"), inputs, cfg, os.path.join(out, "items_master.csv"), lang], "items_master")
        shutil.rmtree(inputs, ignore_errors=True)
    if want("food_stages"):
        ok &= run(PY + [os.path.join(HERE, "food_stages.py"), cfg, os.path.join(out, "food_stages.csv"), lang], "food_stages")
    if want("actions"):
        ok &= run(PY + [os.path.join(HERE, "actions.py"), scripts, os.path.join(out, "actions.csv"), lang], "actions")
    if want("weapon_states", "weapon_transitions"):
        ok &= run(PY + [os.path.join(HERE, "weapon_states.py"), scripts, os.path.join(out, "weapon_states.csv"),
                        os.path.join(out, "weapon_transitions.csv")], "weapon states")
    if want("vehicles"):
        ok &= run(PY + [os.path.join(HERE, "vehicles.py"), cfg, os.path.join(out, "vehicles.csv"), lang], "vehicles")
    if want("catching_items"):
        ok &= run(PY + [os.path.join(HERE, "catching.py"), cfg, os.path.join(out, "catching_items.csv"), lang], "catching_items")
    if want("penetration_materials"):
        ok &= run(PY + [os.path.join(HERE, "penetration.py"), os.path.join(boot, "dz"),
                        os.path.join(out, "penetration_materials.csv")], "penetration_materials")
    if want("ai_perception"):
        ok &= run(PY + [os.path.join(HERE, "ai_perception.py"), cfg, os.path.join(out, "ai_perception.csv")], "ai_perception")
    if want("noise_sources"):
        ok &= run(PY + [os.path.join(HERE, "noise_sources.py"), cfg, os.path.join(out, "noise_sources.csv")], "noise_sources")
    if want("archives"):
        folders = [os.path.join(game, f) for f in ("Addons", "dta", "nasdara", "sakhal") if os.path.isdir(os.path.join(game, f))]
        ok &= run(PY + [os.path.join(HERE, "pbo_inventory.py"), os.path.join(out, "archives.csv"), *folders], "archives")
    if want(*GHIDRA_TABLES):
        ok &= build_native(boot, out)
    return ok


def build_native(boot, out):
    """native_api and native_unmatched from the Ghidra project (several minutes; one Ghidra process at a time)."""
    tasks = os.path.join(HERE, "ghidra", "tasks")
    dec_out, str_out = os.path.join(out, "_ghidra_decompile.txt"), os.path.join(out, "_ghidra_strings.txt")
    ps = ["powershell", "-NoProfile", "-ExecutionPolicy", "Bypass", "-File", os.path.join(HERE, "ghidra", "run_batch.ps1")]
    ok = run(ps + [os.path.join(tasks, "native_api_decompile.txt"), dec_out], "ghidra decompile of the registration functions")
    ok &= run(ps + [os.path.join(tasks, "native_api_strings.txt"), str_out], "ghidra string reads")
    if ok:
        scripts = os.path.join(boot, "scripts_src")
        ok &= run(PY + [os.path.join(HERE, "native_api.py"), dec_out, str_out, scripts, os.path.join(out, "native_api.csv")], "native_api")
        ok &= run(PY + [os.path.join(HERE, "native_gaps.py"), os.path.join(out, "native_api.csv"), scripts,
                        os.path.join(out, "native_unmatched.csv")], "native_unmatched")
    for f in (dec_out, str_out):  # decompiled text is game content: do not leave it next to the tables
        try:
            os.remove(f)
        except OSError:
            pass
    return ok


STAGE_PREFIX = "stage_"
STAGE_MARKER = ".build_tables_stage"


def make_stage(out):
    """A fresh, empty staging folder inside --out. Nothing already in --out is read, cleared or removed (CXR-008): results
    can only come from this run because the folder is new, and only this folder is ever deleted."""
    os.makedirs(out, exist_ok=True)
    stage = tempfile.mkdtemp(prefix=STAGE_PREFIX, dir=out)
    open(os.path.join(stage, STAGE_MARKER), "w").close()
    return stage


def discard_stage(stage):
    """Remove a staging folder made by make_stage - refuses anything without the prefix and the ownership marker."""
    if os.path.basename(stage).startswith(STAGE_PREFIX) and os.path.exists(os.path.join(stage, STAGE_MARKER)):
        shutil.rmtree(stage, ignore_errors=True)


def check_overlaps(boot, out, game):
    """The output folder may not be (or sit inside) an input folder: the tool reads from boot subfolders and the game."""
    inputs = [os.path.join(boot, d) for d in ("cfg", "scripts_src", "ce", "dz")] + [game, DATA]
    for p in inputs:
        p = os.path.abspath(p)
        try:
            if os.path.commonpath([out, p]) in (out, p):
                sys.exit(f"refusing: --out {out} overlaps the input folder {p}")
        except ValueError:  # different drives cannot overlap
            pass


def validate_staged(stage, requested):
    """Every produced table must have rows of the header's width before it is compared or adopted (CXR-009)."""
    sys.path.insert(0, HERE)
    import csv_diff
    ok = True
    for table in sorted(requested):
        p = os.path.join(stage, table + ".csv")
        if os.path.exists(p):
            bad = csv_diff.row_width_problems(p)
            if bad:
                ok = False
                print(f"MALFORMED {table}.csv: {len(bad)} rows with the wrong cell count, first at line {bad[0][0]} "
                      f"({bad[0][1]} cells, header has {bad[0][2]})")
    return ok


def check(out, requested):
    """Compare each requested table with data\\; a missing output or a missing committed table fails."""
    sys.path.insert(0, HERE)
    import csv_diff
    all_ok = True
    for table in sorted(requested):
        new, old = os.path.join(out, table + ".csv"), os.path.join(DATA, table + ".csv")
        if not os.path.exists(new):
            print(f"{table}.csv: NOT PRODUCED by this run")
            all_ok = False
        elif not os.path.exists(old):
            print(f"{table}.csv: not in data\\ yet (new table)")
            all_ok = False
        else:
            all_ok &= csv_diff.compare(old, new, KEYS[table], quiet=False)
    return all_ok


def adopt(out, requested):
    """Copy the requested tables into data\\ - all or none."""
    missing = [t for t in sorted(requested) if not os.path.exists(os.path.join(out, t + ".csv"))]
    if missing:
        print(f"not adopting anything: not produced by this run: {missing}")
        return False
    for table in sorted(requested):
        shutil.copyfile(os.path.join(out, table + ".csv"), os.path.join(DATA, table + ".csv"))
    print(f"adopted {len(requested)} tables into {DATA}")
    return True


def select(only, ghidra):
    """The set of requested tables, validated; returns (requested, skipped)."""
    if only:
        unknown = sorted(set(only) - set(KEYS))
        if unknown:
            sys.exit(f"unknown table names: {unknown}; known: {sorted(KEYS)}")
        requested = set(only)
    else:
        requested = set(KEYS)
    skipped = sorted(requested & GHIDRA_TABLES) if not ghidra else []
    if only and skipped:
        sys.exit(f"{skipped} need --ghidra; refusing to silently skip an explicitly requested table")
    return requested - set(skipped), skipped


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("boot_dir")
    ap.add_argument("--out")
    ap.add_argument("--only", default="")
    ap.add_argument("--check", action="store_true")
    ap.add_argument("--adopt", action="store_true")
    ap.add_argument("--ghidra", action="store_true")
    ap.add_argument("--keep", action="store_true", help="keep the staging folder for inspection")
    ap.add_argument("--game", default=r"F:\SteamLibrary\steamapps\common\DayZ")
    a = ap.parse_args()
    boot = os.path.abspath(a.boot_dir)
    out = os.path.abspath(a.out or os.path.join(boot, "tables"))
    for p in (boot, out):
        if os.path.commonpath([p, PROJECT]) == PROJECT:
            sys.exit(f"refusing: {p} is inside the project folder; extracted game content must live elsewhere")
    only = [x.strip() for x in a.only.split(",") if x.strip()]
    requested, skipped = select(only, a.ghidra)
    check_overlaps(boot, out, a.game)
    stage = make_stage(out)
    try:
        generated_ok = build(boot, stage, a.game, requested, a.ghidra)
        produced = {t for t in requested if os.path.exists(os.path.join(stage, t + ".csv"))}
        wellformed = validate_staged(stage, requested)
        complete = generated_ok and produced == requested and wellformed
        if not complete:
            print(f"BUILD INCOMPLETE: failed generators, malformed tables or tables not produced: {sorted(requested - produced)}")
        if skipped:
            print(f"skipped (need --ghidra): {skipped}")
        print(f"manual tables, not rebuilt: {MANUAL_TABLES}")
        same = True
        if a.check or a.adopt:
            print("comparison with data\\:")
            same = check(stage, requested)
        adopted = True
        if a.adopt:
            if complete:
                adopted = adopt(stage, requested)
            else:
                print("not adopting: the build is incomplete")
                adopted = False
    finally:
        if a.keep:
            print(f"staged tables kept in {stage}")
        else:
            discard_stage(stage)
    ok = complete and (same or a.adopt) and adopted
    sys.exit(0 if ok else 1)


if __name__ == "__main__":
    main()
